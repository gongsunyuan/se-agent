UML_GEN_PROMPT = """你是一个 PlantUML 专家。根据输入的三份设计文档，为以下图表生成标准 PlantUML 代码。

要求：
- 使用 @startuml / @enduml 包裹每个图
- 遵循 UML 2.x 规范
- 中文标注（类名/方法名可保留英文）
- 每个图输出到独立文件
- 输出 JSON：{ "文件名.puml": "@startuml\\n...\\n@enduml" }

需要生成的图表：

1. use-case.puml（用例图）
   - 从需求说明文档的参与者角色章节和用例描述提取
   - actor 用 :名字: 语法，用例用 (用例名) 语法
   - 系统边界用 rectangle 框住

2. component.puml（组件图）
   - 从总体设计的架构组件描述提取
   - 用 component 语法，标注接口（圆括号）和依赖（箭头）

3. deployment.puml（部署图）
   - 从总体设计的技术选型和架构描述推断
   - 用 node 表示物理节点，用 artifact 表示部署单元

4. sequence-borrow.puml（序列图）
   - 从详细设计的借阅流程描述生成
   - actor 表示读者和管理员，participant 表示系统组件
   - 包含 alt/else 分支

5. sequence-return.puml（序列图）
   - 从详细设计的归还流程描述生成

6. sequence-expire.puml（序列图）
   - 从详细设计的凭证超时取消流程描述生成

7. sequence-renew.puml（序列图）
   - 从详细设计的续借流程描述生成

8. class-diagram.puml（类图）
   - 从详细设计的类设计描述生成
   - 包含继承关系、关联关系、接口实现
   - 每个类标注关键属性和方法

9. state-machine.puml（状态机图）
   - 从详细设计的凭证/借阅状态流转描述生成
   - 用 state 语法，标注触发事件

10. er-diagram.puml（ER 图 / 数据模型类图）
    - 从详细设计的数据库表格描述生成
    - 用 entity 语法或 class 语法（stereotype <<entity>>）

11. activity-eligibility.puml（活动图）
    - 从详细设计的资格校验算法描述生成
    - 包含分支节点、判断节点

输入的三份文档将在用户消息中提供。"""

